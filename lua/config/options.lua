local opt = vim.opt

-- =============================================================================
-- 编辑器外观
-- =============================================================================

-- 开启24位真彩色
opt.termguicolors = true

--自定义光标闪烁
opt.guicursor = "n-v-c:block,i-ci-ve:ver25,r-cr:hor20,o:hor50"
  .. ",a:blinkwait700-blinkoff400-blinkon250-Cursor/lCursor"
  .. ",sm:block-blinkwait175-blinkoff150-blinkon175"

-- 显示行号和相对行号
opt.number = true
opt.relativenumber = true

-- 当前行高亮
opt.cursorline = true
opt.cursorlineopt = "number"

-- 第80列高亮线
-- opt.colorcolumn = "80"

-- 显示不可见字符
opt.list = true
opt.listchars = {
  nbsp = "⦸",
  extends = "»",
  precedes = "«",
  tab = "▷⋯",
  trail = "•",
}

-- statusline
opt.laststatus = 0

-- =============================================================================
-- 搜索配置
-- =============================================================================

-- 智能大小写匹配：小写搜索忽略大小写，包含大写时精确匹配
opt.ignorecase = true
opt.smartcase = true

-- 不高亮搜索结果（使用插件管理）
opt.hlsearch = false

-- =============================================================================
-- 缩进和格式化
-- =============================================================================

-- 使用空格代替Tab
opt.expandtab = true

-- Tab显示宽度和缩进宽度
opt.tabstop = 4
opt.shiftwidth = 4
opt.softtabstop = 4

-- 缩进对齐到shiftwidth的整数倍
opt.shiftround = true

-- =============================================================================
-- 折叠配置
-- =============================================================================

-- 基于缩进折叠
opt.foldmethod = "indent"

-- 启动时打开所有折叠
opt.foldlevelstart = 99

-- =============================================================================
-- 补全配置
-- =============================================================================

-- 补全菜单配置
opt.completeopt = "menu,menuone,noselect,popup"

-- 补全菜单最大高度
opt.pumheight = 12

-- 补全菜单透明度
opt.pumblend = 12
--浮动窗口透明度
opt.winblend = 12

-- =============================================================================
-- 窗口和分屏
-- =============================================================================

-- 新窗口默认位置
opt.splitbelow = true
opt.splitright = true

-- =============================================================================
-- 滚动配置
-- =============================================================================

-- 光标距离窗口边缘的行数
opt.scrolloff = 8
opt.sidescrolloff = 8

-- =============================================================================
-- 鼠标配置
-- =============================================================================

-- 启用鼠标
opt.mouse = "a"

-- =============================================================================
-- 剪切板配置
-- =============================================================================

-- 与系统剪切板同步
vim.api.nvim_create_autocmd("UIEnter", {
  callback = function()
    vim.o.clipboard = "unnamedplus"
  end,
})

-- =============================================================================
-- 撤销和历史
-- =============================================================================

-- 持久化撤销历史
opt.undofile = true

-- =============================================================================
-- 其他配置
-- =============================================================================

-- 不换行显示
opt.wrap = false
